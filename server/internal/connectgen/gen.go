// Package connectgen generates ConnectRPC server adapters and streaming
// procedure tables from gitslice.core.v1 protobuf service descriptors.
package connectgen

import (
	"bytes"
	"fmt"
	"go/format"
	"reflect"
	"sort"

	_ "gitslice.io/gitslice/proto/core/v1"
	"gitslice.io/gitslice/service"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/reflect/protoregistry"
)

const targetProtoPackage = "gitslice.core.v1"

type serviceSpec struct {
	Name         string
	HandlerField string
	Methods      []methodSpec
}

type methodSpec struct {
	Name            string
	FullProcedure   string
	InputType       string
	OutputType      string
	ClientStreaming bool
	ServerStreaming bool
}

// Generate returns the gofmt-formatted Go source for server/connect_adapters_gen.go.
func Generate() ([]byte, error) {
	handlerFields := handlerFieldByServiceType()

	var services []serviceSpec
	var streaming []string
	var walkErr error

	protoregistry.GlobalFiles.RangeFilesByPackage(targetProtoPackage, func(fd protoreflect.FileDescriptor) bool {
		svcs := fd.Services()
		for i := 0; i < svcs.Len(); i++ {
			sd := svcs.Get(i)
			svcName := string(sd.Name())
			fieldName, ok := handlerFields[svcName]
			if !ok {
				walkErr = fmt.Errorf("service.Handlers has no *service.%s field for proto service %s", svcName, sd.FullName())
				return false
			}
			spec := serviceSpec{
				Name:         svcName,
				HandlerField: fieldName,
			}
			methods := sd.Methods()
			for j := 0; j < methods.Len(); j++ {
				md := methods.Get(j)
				inPkg := string(md.Input().ParentFile().Package())
				outPkg := string(md.Output().ParentFile().Package())
				if inPkg != targetProtoPackage || outPkg != targetProtoPackage {
					walkErr = fmt.Errorf("method %s uses message outside %s (%s, %s)", md.FullName(), targetProtoPackage, inPkg, outPkg)
					return false
				}
				proc := fmt.Sprintf("/%s/%s", sd.FullName(), md.Name())
				mSpec := methodSpec{
					Name:            string(md.Name()),
					FullProcedure:   proc,
					InputType:       string(md.Input().Name()),
					OutputType:      string(md.Output().Name()),
					ClientStreaming: md.IsStreamingClient(),
					ServerStreaming: md.IsStreamingServer(),
				}
				if mSpec.ClientStreaming || mSpec.ServerStreaming {
					streaming = append(streaming, proc)
				}
				spec.Methods = append(spec.Methods, mSpec)
			}
			services = append(services, spec)
		}
		return true
	})
	if walkErr != nil {
		return nil, walkErr
	}

	sort.Slice(services, func(i, j int) bool { return services[i].Name < services[j].Name })
	sort.Strings(streaming)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by server/internal/connectgen; DO NOT EDIT.\n\n")
	buf.WriteString("package server\n\n")
	buf.WriteString("import (\n")
	buf.WriteString("\t\"context\"\n")
	buf.WriteString("\t\"net/http\"\n\n")
	buf.WriteString("\t\"connectrpc.com/connect\"\n")
	buf.WriteString("\tcorev1 \"gitslice.io/gitslice/proto/core/v1\"\n")
	buf.WriteString("\tcorev1connect \"gitslice.io/gitslice/proto/core/v1/corev1connect\"\n")
	buf.WriteString("\t\"gitslice.io/gitslice/service\"\n")
	buf.WriteString(")\n\n")

	buf.WriteString("// streamingProcedures lists every client-, server-, or bidi-streaming RPC\n")
	buf.WriteString("// procedure in gitslice.core.v1 so HTTP unary read/write deadlines skip them.\n")
	buf.WriteString("var streamingProcedures = map[string]bool{\n")
	for _, proc := range streaming {
		fmt.Fprintf(&buf, "\t%q: true,\n", proc)
	}
	buf.WriteString("}\n\n")

	buf.WriteString("func mountConnectServices(mount func(string, http.Handler), handlers *service.Handlers, limiters *serverLimiters, opts ...connect.HandlerOption) {\n")
	for _, svc := range services {
		adapterExpr := fmt.Sprintf("connect%sAdapter{svc: handlers.%s}", svc.Name, svc.HandlerField)
		if svc.Name == "TriggerRunService" {
			fmt.Fprintf(&buf, "\ttriggerRunOpts := append(append([]connect.HandlerOption{}, opts...), connect.WithInterceptors(connectTriggerRunFailureInterceptor(limiters)))\n")
			fmt.Fprintf(&buf, "\tmount(corev1connect.New%sHandler(%s, triggerRunOpts...))\n", svc.Name, adapterExpr)
		} else {
			fmt.Fprintf(&buf, "\tmount(corev1connect.New%sHandler(%s, opts...))\n", svc.Name, adapterExpr)
		}
	}
	buf.WriteString("}\n")

	for _, svc := range services {
		adapterName := fmt.Sprintf("connect%sAdapter", svc.Name)
		fmt.Fprintf(&buf, "\ntype %s struct {\n\tsvc *service.%s\n}\n", adapterName, svc.Name)
		for _, m := range svc.Methods {
			switch {
			case !m.ClientStreaming && !m.ServerStreaming:
				fmt.Fprintf(&buf, "\nfunc (a %s) %s(ctx context.Context, req *connect.Request[corev1.%s]) (*connect.Response[corev1.%s], error) {\n", adapterName, m.Name, m.InputType, m.OutputType)
				fmt.Fprintf(&buf, "\treturn connectResponse(a.svc.%s(ctx, req.Msg))\n}\n", m.Name)
			case !m.ClientStreaming && m.ServerStreaming:
				fmt.Fprintf(&buf, "\nfunc (a %s) %s(ctx context.Context, req *connect.Request[corev1.%s], stream *connect.ServerStream[corev1.%s]) error {\n", adapterName, m.Name, m.InputType, m.OutputType)
				fmt.Fprintf(&buf, "\treturn connectError(a.svc.%s(req.Msg, newConnectServerStream(ctx, stream)))\n}\n", m.Name)
			case m.ClientStreaming && !m.ServerStreaming:
				fmt.Fprintf(&buf, "\nfunc (a %s) %s(ctx context.Context, stream *connect.ClientStream[corev1.%s]) (*connect.Response[corev1.%s], error) {\n", adapterName, m.Name, m.InputType, m.OutputType)
				fmt.Fprintf(&buf, "\tadapter := newConnectClientStream[corev1.%s, corev1.%s](ctx, stream)\n", m.InputType, m.OutputType)
				fmt.Fprintf(&buf, "\tif err := a.svc.%s(adapter); err != nil {\n\t\treturn nil, connectError(err)\n\t}\n\treturn adapter.finish()\n}\n", m.Name)
			default:
				fmt.Fprintf(&buf, "\nfunc (a %s) %s(ctx context.Context, stream *connect.BidiStream[corev1.%s, corev1.%s]) error {\n", adapterName, m.Name, m.InputType, m.OutputType)
				fmt.Fprintf(&buf, "\treturn connectError(a.svc.%s(newConnectBidiStream(ctx, stream)))\n}\n", m.Name)
			}
		}
	}

	return format.Source(buf.Bytes())
}

func handlerFieldByServiceType() map[string]string {
	t := reflect.TypeFor[service.Handlers]()
	out := make(map[string]string, t.NumField())
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if f.Type.Kind() == reflect.Pointer && f.Type.Elem().PkgPath() == "gitslice.io/gitslice/service" {
			out[f.Type.Elem().Name()] = f.Name
		}
	}
	return out
}
