import { Link, Navigate } from "@tanstack/react-router";
import { useEffect, useRef, useState } from "react";

import { useAppAuth } from "../auth/AppAuthProvider";
import { clearReturnTo, peekReturnTo } from "../auth/returnTo";
import { AgentSignInForm } from "../components/AgentSignInForm";
import { AuthFrame } from "../components/AuthFrame";
import { isSafeReturnPath } from "../lib/agentSession";

function extractFragmentKey(): string | null {
  if (typeof window === "undefined") {
    return null;
  }
  const hash = window.location.hash.replace(/^#/, "");
  if (!hash) {
    return null;
  }
  const params = new URLSearchParams(hash);
  const key = (params.get("key") ?? "").trim();
  return key || null;
}

function resolveTargetPath(fallbackReturnTo: string | null): string {
  if (typeof window !== "undefined") {
    const queryReturnTo = new URLSearchParams(window.location.search).get("returnTo");
    if (isSafeReturnPath(queryReturnTo)) {
      return queryReturnTo;
    }
  }
  if (isSafeReturnPath(fallbackReturnTo)) {
    return fallbackReturnTo;
  }
  return "/";
}

// Handles browser links generated by `gs auth web-login` (`/agent-login#key=...`)
// as well as direct API-key sign-in. The key rides in the URL fragment so it is
// never sent to servers, proxies, or logs, and is read in an effect after
// hydration so SSR and initial client markup always match.
export function AgentLoginPage() {
  const { isLoaded, isSignedIn, signInWithAgentKey } = useAppAuth();
  const [returnTo] = useState(peekReturnTo);
  const [exchanging, setExchanging] = useState(false);
  const [handledFragment, setHandledFragment] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const startedRef = useRef(false);

  useEffect(() => {
    if (startedRef.current) {
      return;
    }
    const fragmentKey = extractFragmentKey();
    if (!fragmentKey) {
      return;
    }
    startedRef.current = true;
    setHandledFragment(true);
    // Strip the credential from the address bar and session history immediately.
    const cleanUrl = `${window.location.pathname}${window.location.search}`;
    window.history.replaceState(null, "", cleanUrl);

    let cancelled = false;
    setExchanging(true);
    setError(null);
    void signInWithAgentKey(fragmentKey)
      .then(() => {
        if (cancelled) {
          return;
        }
        clearReturnTo();
        window.location.replace(resolveTargetPath(returnTo));
      })
      .catch((caught) => {
        if (cancelled) {
          return;
        }
        setExchanging(false);
        setError(caught instanceof Error ? caught.message : "Could not sign in with that link.");
      });

    return () => {
      cancelled = true;
    };
  }, [returnTo, signInWithAgentKey]);

  if (exchanging) {
    return (
      <AuthFrame title="Signing in as agent">
        <p className="text-sm text-slate-600 dark:text-zinc-400">
          Verifying agent credential and starting a short-lived web session...
        </p>
      </AuthFrame>
    );
  }

  if (isLoaded && isSignedIn && !handledFragment) {
    const target = resolveTargetPath(returnTo);
    clearReturnTo();
    if (target !== "/") {
      window.location.replace(target);
      return (
        <AuthFrame title="Signed in">
          <p className="text-sm text-slate-600 dark:text-zinc-400">Returning to your page...</p>
        </AuthFrame>
      );
    }
    return <Navigate replace to="/" />;
  }

  return (
    <AuthFrame title="Agent sign in">
      <AgentSignInForm
        initialError={error}
        onSignedIn={() => {
          const target = resolveTargetPath(returnTo);
          clearReturnTo();
          window.location.replace(target);
        }}
      />
      <p className="mt-4 text-xs text-slate-500 dark:text-zinc-400">
        Signing in as a human?{" "}
        <Link
          className="font-medium text-slate-700 underline underline-offset-2 hover:text-slate-900 dark:text-zinc-300 dark:hover:text-zinc-100"
          reloadDocument
          to="/login"
        >
          Use email or GitHub
        </Link>
        .
      </p>
    </AuthFrame>
  );
}
