import { describe, expect, it } from "vitest";

import { fileFingerprint, isGeneratedFile, isGeneratedPath, isViewed, loadViewed, saveViewed } from "./reviewState";
import { parseDiff } from "./parseDiff";

function memoryStorage(): Storage {
  const map = new Map<string, string>();
  return {
    get length() {
      return map.size;
    },
    clear: () => map.clear(),
    getItem: (key: string) => map.get(key) ?? null,
    key: (index: number) => [...map.keys()][index] ?? null,
    removeItem: (key: string) => void map.delete(key),
    setItem: (key: string, value: string) => void map.set(key, value)
  };
}

function diffOf(path: string, body: string[]) {
  return parseDiff(
    [`diff --git a/${path} b/${path}`, `--- a/${path}`, `+++ b/${path}`, `@@ -1,${body.length} +1,${body.length} @@`, ...body, ""].join("\n"),
    [path]
  )[0];
}

describe("generated files", () => {
  it("knows generated and lock files by name", () => {
    for (const path of [
      "proto/core/v1/auth.pb.go",
      "proto/core/v1/auth.pb.gw.go",
      "proto/core/v1/corev1connect/auth.connect.go",
      "web/src/gen/proto/core/v1/auth_pb.ts",
      "api/x_pb2.py",
      "web/dist/app.min.js",
      "web/package-lock.json",
      "go.sum",
      "deep/dir/pnpm-lock.yaml",
      "Cargo.lock",
      "src/api.generated.ts",
      "internal/store_generated.go"
    ]) {
      expect(isGeneratedPath(path), path).toBe(true);
    }
    for (const path of ["main.go", "web/src/routes/ChangesetsPage.tsx", "docs/package-lock-notes.md", "generator.go", "go.mod", "README.md"]) {
      expect(isGeneratedPath(path), path).toBe(false);
    }
  });

  it("knows a generated file by the marker its tool writes at the top", () => {
    const marked = diffOf("internal/rpc.go", ["+// Code generated by protoc-gen-go. DO NOT EDIT.", " package rpc", "-old", "+new"]);
    expect(isGeneratedFile(marked)).toBe(true);
    const plain = diffOf("internal/rpc.go", [" // Package rpc does things.", " package rpc", "-old", "+new"]);
    expect(isGeneratedFile(plain)).toBe(false);
    // A mention further down the file is not a header.
    const late = diffOf("notes.go", [...Array.from({ length: 20 }, (_, i) => ` line ${i}`), "+// do not edit this by hand"]);
    expect(isGeneratedFile(late)).toBe(false);
  });
});

describe("viewed files", () => {
  const before = diffOf("a.ts", [" keep", "-old", "+new"]);

  it("is viewed only while the file still shows what it showed", () => {
    const viewed = { "a.ts": fileFingerprint(before) };
    expect(isViewed(before, viewed)).toBe(true);
    // The next patchset changes the file: it needs another look.
    const after = diffOf("a.ts", [" keep", "-old", "+newer"]);
    expect(fileFingerprint(after)).not.toBe(fileFingerprint(before));
    expect(isViewed(after, viewed)).toBe(false);
    expect(isViewed(diffOf("b.ts", [" keep"]), viewed)).toBe(false);
  });

  it("keeps a mark on a file whose diff has not loaded, to check once it does", () => {
    const pending = { path: "a.ts", lines: [] };
    expect(fileFingerprint(pending)).toBe("");
    expect(isViewed(pending, { "a.ts": "whatever" })).toBe(true);
    expect(isViewed(pending, {})).toBe(false);
  });

  it("remembers marks per changeset, forgets a changeset with none, and keeps the latest 40", () => {
    const storage = memoryStorage();
    expect(loadViewed("cs_1", storage)).toEqual({});
    saveViewed("cs_1", { "a.ts": "x" }, storage, 1);
    saveViewed("cs_2", { "b.ts": "y" }, storage, 2);
    expect(loadViewed("cs_1", storage)).toEqual({ "a.ts": "x" });
    expect(loadViewed("cs_2", storage)).toEqual({ "b.ts": "y" });
    saveViewed("cs_1", {}, storage, 3);
    expect(loadViewed("cs_1", storage)).toEqual({});
    expect(loadViewed("cs_2", storage)).toEqual({ "b.ts": "y" });

    for (let i = 0; i < 50; i++) {
      saveViewed(`many_${i}`, { f: "1" }, storage, 100 + i);
    }
    expect(loadViewed("many_49", storage)).toEqual({ f: "1" });
    expect(loadViewed("many_9", storage)).toEqual({});
    expect(loadViewed("cs_2", storage)).toEqual({});
  });

  it("does nothing without a scope or storage, and survives a damaged record", () => {
    const storage = memoryStorage();
    saveViewed("", { a: "1" }, storage);
    expect(storage.length).toBe(0);
    expect(loadViewed("cs_1", undefined)).toEqual({});
    storage.setItem("gitslice.viewedFiles.v1", "{not json");
    expect(loadViewed("cs_1", storage)).toEqual({});
    saveViewed("cs_1", { a: "1" }, storage, 5);
    expect(loadViewed("cs_1", storage)).toEqual({ a: "1" });
    storage.setItem("gitslice.viewedFiles.v1", "[1,2]");
    expect(loadViewed("cs_1", storage)).toEqual({});
  });
});
