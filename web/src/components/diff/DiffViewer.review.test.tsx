import "@testing-library/jest-dom/vitest";

import { cleanup, fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import { DiffViewer } from "./DiffViewer";

function fileDiff(path: string, change: string, header = " keep") {
  return [
    `diff --git a/${path} b/${path}`,
    `--- a/${path}`,
    `+++ b/${path}`,
    "@@ -1,2 +1,2 @@",
    header,
    `-old ${change}`,
    `+new ${change}`
  ];
}

function diffOf(changes: Record<string, string>) {
  return [...Object.entries(changes).flatMap(([path, change]) => fileDiff(path, change)), ""].join("\n");
}


// scope is null for a viewer given no changeset to scope its marks to.
function viewer(changes: Record<string, string> = { "a.ts": "a", "b.ts": "b", "proto/x.pb.go": "gen" }, scope: string | null = "cs_1") {
  return (
    <DiffViewer
      diffResponse={{ changedPaths: Object.keys(changes), diff: diffOf(changes) }}
      error={null}
      isError={false}
      isLoading={false}
      viewedScope={scope ?? undefined}
    />
  );
}

const body = (change: string) => screen.queryByText(`+new ${change}`);

beforeEach(() => {
  // Choosing a file scrolls to it; jsdom has no layout to scroll.
  Element.prototype.scrollIntoView = vi.fn();
  window.localStorage.clear();
});

afterEach(() => {
  cleanup();
  window.localStorage.clear();
  vi.useRealTimers();
});

describe("reviewing a changeset's diff", () => {
  it("folds a file by hand, and opens it again", () => {
    render(viewer());
    expect(body("a")).toBeInTheDocument();

    fireEvent.click(screen.getByRole("button", { name: "Collapse a.ts" }));
    expect(body("a")).toBeNull();
    expect(screen.getByRole("button", { name: "Expand a.ts" })).toHaveAttribute("aria-expanded", "false");
    // The other files are as they were.
    expect(body("b")).toBeInTheDocument();

    fireEvent.click(screen.getByRole("button", { name: "Expand a.ts" }));
    expect(body("a")).toBeInTheDocument();
    expect(screen.getByRole("button", { name: "Collapse a.ts" })).toHaveAttribute("aria-expanded", "true");
  });

  it("starts a generated file folded, says so, and opens it on request", () => {
    render(viewer());
    expect(screen.getAllByText("Generated")).toHaveLength(1);
    expect(body("gen")).toBeNull();
    expect(screen.getByRole("button", { name: "Expand proto/x.pb.go" })).toBeInTheDocument();

    fireEvent.click(screen.getByRole("button", { name: "Expand proto/x.pb.go" }));
    expect(body("gen")).toBeInTheDocument();
  });

  it("starts a file folded when a tool's header says it wrote it, whatever its name", () => {
    const diff = [
      "diff --git a/rpc.go b/rpc.go",
      "--- a/rpc.go",
      "+++ b/rpc.go",
      "@@ -1,2 +1,2 @@",
      " // Code generated by a tool. DO NOT EDIT.",
      "-old rpc",
      "+new rpc",
      ""
    ].join("\n");
    render(<DiffViewer diffResponse={{ changedPaths: ["rpc.go"], diff }} error={null} isError={false} isLoading={false} />);
    expect(screen.getByText("Generated")).toBeInTheDocument();
    expect(body("rpc")).toBeNull();
  });

  it("marking a file viewed folds it, counts it and ticks it in the tree; unmarking opens it", () => {
    render(viewer());
    expect(screen.getByText("0 of 3 viewed")).toBeInTheDocument();

    fireEvent.click(screen.getByRole("checkbox", { name: "Viewed a.ts" }));
    expect(screen.getByRole("checkbox", { name: "Viewed a.ts" })).toBeChecked();
    expect(body("a")).toBeNull();
    expect(screen.getByText("1 of 3 viewed")).toBeInTheDocument();
    expect(screen.getAllByRole("img", { name: "viewed" })).toHaveLength(1);

    fireEvent.click(screen.getByRole("checkbox", { name: "Viewed a.ts" }));
    expect(screen.getByRole("checkbox", { name: "Viewed a.ts" })).not.toBeChecked();
    expect(body("a")).toBeInTheDocument();
    expect(screen.getByText("0 of 3 viewed")).toBeInTheDocument();
    expect(screen.queryByRole("img", { name: "viewed" })).toBeNull();
  });

  it("remembers what was viewed for that changeset only", () => {
    const first = render(viewer());
    fireEvent.click(screen.getByRole("checkbox", { name: "Viewed a.ts" }));
    first.unmount();

    // The same changeset, opened again: still viewed and folded.
    const again = render(viewer());
    expect(screen.getByRole("checkbox", { name: "Viewed a.ts" })).toBeChecked();
    expect(body("a")).toBeNull();
    expect(screen.getByText("1 of 3 viewed")).toBeInTheDocument();
    again.unmount();

    // Another changeset starts with nothing viewed.
    render(viewer(undefined, "cs_other"));
    expect(screen.getByRole("checkbox", { name: "Viewed a.ts" })).not.toBeChecked();
    expect(body("a")).toBeInTheDocument();
  });

  it("asks for another look at a file that changed since it was viewed", () => {
    const first = render(viewer());
    fireEvent.click(screen.getByRole("checkbox", { name: "Viewed a.ts" }));
    fireEvent.click(screen.getByRole("checkbox", { name: "Viewed b.ts" }));
    first.unmount();

    // A new patchset changes a.ts and leaves b.ts.
    render(viewer({ "a.ts": "a, reworked", "b.ts": "b", "proto/x.pb.go": "gen" }));
    expect(screen.getByRole("checkbox", { name: "Viewed a.ts" })).not.toBeChecked();
    expect(body("a, reworked")).toBeInTheDocument();
    expect(screen.getByRole("checkbox", { name: "Viewed b.ts" })).toBeChecked();
    expect(body("b")).toBeNull();
    expect(screen.getByText("1 of 3 viewed")).toBeInTheDocument();
  });

  it("without a changeset to scope them to, marks last for the page only", () => {
    const first = render(viewer(undefined, null));
    fireEvent.click(screen.getByRole("checkbox", { name: "Viewed a.ts" }));
    expect(screen.getByRole("checkbox", { name: "Viewed a.ts" })).toBeChecked();
    expect(window.localStorage.getItem("gitslice.viewedFiles.v1")).toBeNull();
    first.unmount();
    render(viewer(undefined, null));
    expect(screen.getByRole("checkbox", { name: "Viewed a.ts" })).not.toBeChecked();
  });

  it("moves between files with j and k, and marks the current one viewed with v", async () => {
    render(viewer());
    const current = () => screen.getByRole("button", { current: true });
    const key = (k: string, target: Element | Window = window) => fireEvent.keyDown(target, { key: k });
    expect(current()).toHaveTextContent("a.ts");

    key("j");
    expect(current()).toHaveTextContent("b.ts");
    key("j");
    expect(current()).toHaveTextContent("x.pb.go");
    key("j"); // past the last file: stays
    expect(current()).toHaveTextContent("x.pb.go");
    key("k");
    expect(current()).toHaveTextContent("b.ts");

    key("v");
    expect(screen.getByRole("checkbox", { name: "Viewed b.ts" })).toBeChecked();
    expect(body("b")).toBeNull();
    key("v");
    expect(screen.getByRole("checkbox", { name: "Viewed b.ts" })).not.toBeChecked();
    // Choosing a file scrolls to it, after the click that chose it.
    await waitFor(() => expect(Element.prototype.scrollIntoView).toHaveBeenCalled());
  });

  it("leaves j, k and v alone while typing, and with a modifier held", () => {
    render(
      <>
        <input aria-label="search" />
        {viewer()}
      </>
    );
    const current = () => screen.getByRole("button", { current: true });
    fireEvent.keyDown(screen.getByLabelText("search"), { key: "j" });
    fireEvent.keyDown(screen.getByLabelText("search"), { key: "v" });
    fireEvent.keyDown(window, { key: "j", ctrlKey: true });
    fireEvent.keyDown(window, { key: "v", metaKey: true });
    expect(current()).toHaveTextContent("a.ts");
    expect(screen.getByText("0 of 3 viewed")).toBeInTheDocument();
  });

  it("does not offer a viewed mark for a file whose diff has not loaded", () => {
    render(
      <DiffViewer
        error={null}
        fileStates={[{ path: "late.ts", status: "pending" }]}
        isError={false}
        isLoading={false}
        viewedScope="cs_1"
      />
    );
    expect(screen.queryByRole("checkbox")).toBeNull();
    // It can still be folded.
    expect(within(screen.getByRole("article")).getByRole("button", { name: /Collapse late.ts/ })).toBeInTheDocument();
  });
});

